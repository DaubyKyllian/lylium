        <h2>1. Objet</h2>
        <p>La présente Politique précise les modalités de livraison, de retour et de remboursement applicables aux commandes effectuées sur le site LYLIUM.</p>
        <p>Elle complète les <a href="/cgv.php" class="link-underline">Conditions Générales de Vente</a> de LYLIUM.</p>

        <h2>2. Zones de livraison</h2>
        <p>LYLIUM livre les commandes dans les zones géographiques indiquées au moment de la commande.</p>
        <p>Dans un premier temps, LYLIUM peut limiter ses livraisons à la France métropolitaine.</p>
        <p>Les éventuelles extensions de livraison vers les territoires ultramarins ou l'international seront indiquées directement sur le site.</p>
        <p>Certaines destinations peuvent être exclues en raison de contraintes logistiques ou réglementaires.</p>

        <h2>3. Modes de livraison</h2>
        <p>Les modes de livraison disponibles sont présentés au client lors de la commande.</p>
        <p>Selon la destination et les produits commandés, LYLIUM peut proposer différents modes de livraison par l'intermédiaire de transporteurs partenaires.</p>
        <p>Le choix du mode de livraison appartient au client parmi les options proposées au moment de la commande.</p>

        <h2>4. Frais de livraison</h2>
        <p>Les frais de livraison applicables sont indiqués au client avant la validation définitive de la commande.</p>
        <p>Le montant des frais peut varier notamment selon :</p>
        <ul>
            <li>la destination ;</li>
            <li>le mode de livraison sélectionné ;</li>
            <li>le poids ou les dimensions du colis ;</li>
            <li>les conditions commerciales applicables à la commande.</li>
        </ul>
        <p>Lorsque la livraison est offerte, cette information est clairement indiquée au moment de la commande.</p>

        <h2>5. Délais de livraison</h2>
        <p>Le délai de livraison estimé est communiqué au client avant la validation de la commande.</p>
        <p>Ce délai peut dépendre notamment :</p>
        <ul>
            <li>de la disponibilité du produit ;</li>
            <li>du délai de préparation ;</li>
            <li>du mode de livraison choisi ;</li>
            <li>de la destination ;</li>
            <li>du transporteur.</li>
        </ul>
        <p>Lorsque certains produits sont fabriqués à la demande ou proposés en précommande, un délai spécifique peut être indiqué sur la fiche produit avant l'achat.</p>
        <p>LYLIUM informe le client de tout retard significatif dont elle aurait connaissance.</p>

        <h2>6. Préparation des commandes</h2>
        <p>LYLIUM apporte une attention particulière à la préparation des commandes.</p>
        <p>Avant expédition, les produits peuvent faire l'objet d'un contrôle portant notamment sur leur conformité et leur état.</p>
        <p>Les produits sont emballés de manière à limiter les risques de détérioration pendant le transport.</p>

        <h2>7. Suivi de la livraison</h2>
        <p>Lorsque le mode de livraison le permet, un numéro de suivi peut être communiqué au client par e-mail ou via son espace personnel.</p>
        <p>Le client peut ainsi suivre l'avancement de son colis selon les informations communiquées par le transporteur.</p>

        <h2>8. Réception de la commande</h2>
        <p>Le client est invité à vérifier l'état apparent du colis lors de sa réception.</p>
        <p>En cas de colis visiblement endommagé, le client est invité à signaler l'anomalie au transporteur et à contacter LYLIUM dans les meilleurs délais.</p>
        <p>Cette recommandation ne prive pas le client de ses droits légaux.</p>

        <h2>9. Colis non réceptionné ou retourné à LYLIUM</h2>
        <p>En cas d'absence du client, de problème d'adresse ou de non-récupération du colis dans les délais prévus par le transporteur, le colis peut être retourné à LYLIUM.</p>
        <p>LYLIUM contactera alors le client afin de déterminer les modalités permettant, lorsque cela est possible, une nouvelle expédition.</p>
        <p>Les éventuels frais supplémentaires résultant d'une erreur dans les informations fournies par le client ou d'une situation imputable à celui-ci pourront être facturés dans les limites autorisées par la réglementation applicable.</p>

        <h2>10. Droit de rétractation</h2>
        <p>Conformément à la réglementation applicable, le consommateur dispose, en principe, d'un délai de quatorze (14) jours à compter de la réception du produit pour exercer son droit de rétractation.</p>
        <p>Le client peut exercer ce droit en contactant LYLIUM par écrit, notamment par e-mail, ou en utilisant le formulaire de rétractation disponible sur le site.</p>
        <p>Le client doit ensuite retourner le produit dans les conditions et délais prévus par la réglementation applicable.</p>
        <p>Un <a href="/retractation.php" class="link-underline">formulaire de rétractation</a> est mis à disposition à cet effet.</p>

        <h2>11. Conditions de retour</h2>
        <p>Les produits retournés doivent être manipulés avec soin.</p>
        <p>Le client peut essayer un vêtement dans les conditions permettant normalement d'en apprécier la nature, les caractéristiques et le bon fonctionnement.</p>
        <p>Le client peut être responsable de la dépréciation du produit résultant de manipulations qui excéderaient celles nécessaires à cet examen.</p>
        <p>Lorsque cela est possible, LYLIUM recommande de retourner les produits dans leur emballage d'origine afin de garantir leur protection pendant le transport.</p>
        <p>L'absence de l'emballage d'origine ne prive pas automatiquement le consommateur de son droit de rétractation lorsque celui-ci est applicable.</p>

        <h2>12. Frais de retour</h2>
        <p>Sauf indication contraire de LYLIUM ou disposition légale contraire, les frais directs de retour liés à l'exercice du droit de rétractation sont à la charge du client.</p>
        <p>Lorsque le retour est effectué en raison d'un produit défectueux, non conforme ou relevant d'une garantie légale, LYLIUM prend en charge les frais dans les conditions prévues par la réglementation applicable.</p>

        <h2>13. Produits personnalisés</h2>
        <p>Lorsqu'un produit est confectionné selon les spécifications du client ou nettement personnalisé, le droit de rétractation peut ne pas s'appliquer lorsque les conditions prévues par la réglementation sont réunies.</p>
        <p>Les produits concernés et les conditions applicables sont clairement identifiés avant la validation de la commande.</p>
        <p>Une personnalisation légère ou une option proposée par LYLIUM ne constitue pas nécessairement une exclusion du droit de rétractation : l'application de cette exception dépend des caractéristiques concrètes du produit et de la réglementation applicable.</p>

        <h2>14. Retour d'un produit défectueux ou non conforme</h2>
        <p>Lorsqu'un produit présente un défaut de conformité ou relève d'un vice caché, le client bénéficie des garanties légales applicables.</p>
        <p>Le client peut contacter LYLIUM afin de signaler le problème et de recevoir les instructions nécessaires au traitement de sa demande.</p>
        <p>LYLIUM pourra demander des informations ou photographies permettant de comprendre le problème rencontré.</p>
        <p>Cette demande ne limite pas les droits légaux du client.</p>

        <h2>15. Remboursement</h2>
        <p>Lorsque le client exerce valablement son droit de rétractation, LYLIUM procède au remboursement conformément à la réglementation applicable.</p>
        <p>Le remboursement est effectué en utilisant le même moyen de paiement que celui utilisé lors de la commande, sauf accord contraire du client et sous réserve des dispositions légales applicables.</p>
        <p>LYLIUM peut différer le remboursement jusqu'à récupération du produit ou jusqu'à réception par LYLIUM d'une preuve d'expédition du produit retourné, la date retenue étant celle du premier de ces événements.</p>

        <h2>16. Échange</h2>
        <p>LYLIUM peut proposer un échange de produit lorsque cette possibilité est indiquée sur le site ou acceptée par le service client.</p>
        <p>L'échange peut notamment être proposé en cas de problème de taille ou de défaut, sous réserve de la disponibilité du produit concerné.</p>
        <p>Lorsqu'un échange n'est pas possible, les droits du client en matière de remboursement ou de garanties légales restent applicables.</p>

        <h2>17. Retour après échange</h2>
        <p>Lorsqu'un échange a été accepté par LYLIUM, les modalités de retour du produit initial et d'expédition du nouveau produit sont communiquées au client au moment de la demande.</p>

